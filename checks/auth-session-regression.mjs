import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const storage = new Map();
globalThis.window = { location: { pathname: '/resumes' } };
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,v), removeItem: k => storage.delete(k) };
const { outputText } = ts.transpileModule(readFileSync('lib/api-client.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const load = () => import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}#${Math.random()}`);
const token = `header.${Buffer.from(JSON.stringify({sub:'u1',exp:Math.floor(Date.now()/1000)+600})).toString('base64url')}.signature`;
const user = { id: 'u1', name: '测试', email: 'test@example.com' };
let {api} = await load();
globalThis.fetch = async () => ({ok:true,json:async()=>({data:user,access_token:token})});
await api.login(user.email,'password');
assert.equal(storage.get('auth_token'),token);
({api} = await load()); // 模拟重新打开页面，重新加载客户端模块。
globalThis.fetch = async () => { throw new TypeError('network unavailable'); };
assert.deepEqual(await api.me(),user);
globalThis.fetch = async () => ({ok:false,status:503});
assert.deepEqual(await api.me(),user);
const expired = `h.${Buffer.from(JSON.stringify({sub:'u1',exp:1})).toString('base64url')}.s`;
storage.set('auth_token',expired);storage.set('auth_user',JSON.stringify({token:expired,user}));
assert.equal(await api.me(),null);
storage.set('auth_token',token);storage.set('auth_user',JSON.stringify({token,user}));
globalThis.fetch = async () => ({ok:false,status:401});
assert.equal(await api.me(),null);assert.equal(storage.size,0);
storage.set('auth_token',token);
globalThis.fetch = async () => { storage.set('auth_token','new-login-token');return {ok:false,status:401}; };
await api.me();assert.equal(storage.get('auth_token'),'new-login-token');
console.log('登录持久化、重载恢复、网络故障、过期、401 和旧请求竞态检查通过');
